#[derive(Clone, Debug, Deserialize)]
pub struct MonitorConfig {
    pub id: String,
    pub name: String,
    #[serde(default)]
    pub order: Option<i64>,
    #[serde(
        default = "default_interval_seconds",
        rename = "interval",
        alias = "interval_seconds"
    )]
    pub interval_seconds: u64,
    #[serde(
        default = "default_timeout_seconds",
        rename = "timeout",
        alias = "timeout_seconds"
    )]
    pub timeout_seconds: u64,
    #[serde(
        default = "default_slow_response_threshold_ms",
        rename = "slow_ms",
        alias = "slow_response_threshold_ms"
    )]
    pub slow_response_threshold_ms: Option<u64>,
    #[serde(
        default,
        rename = "exclude_status",
        alias = "exclude_from_aggregate_status"
    )]
    pub exclude_from_aggregate_status: bool,
    #[serde(default)]
    pub hide_target: bool,
    #[serde(flatten)]
    pub target: MonitorTarget,
    #[serde(default = "default_response_codes")]
    pub response_codes: BTreeMap<i64, ResponseCodeStatus>,
}

fn default_response_codes() -> BTreeMap<i64, ResponseCodeStatus> {
    BTreeMap::from([
        (0, ResponseCodeStatus::Operational),
        (1, ResponseCodeStatus::Degraded),
        (2, ResponseCodeStatus::Down),
    ])
}

fn default_interval_seconds() -> u64 {
    60
}

fn default_timeout_seconds() -> u64 {
    10
}

fn default_slow_response_threshold_ms() -> Option<u64> {
    Some(500)
}

#[derive(Clone, Debug, Deserialize)]
#[serde(tag = "type", rename_all = "lowercase")]
pub enum MonitorTarget {
    Http {
        url: String,
        #[serde(default = "default_method")]
        method: String,
        #[serde(default, rename = "status_codes", alias = "accepted_status_codes")]
        accepted_status_codes: Vec<u16>,
        #[serde(default)]
        headers: BTreeMap<String, String>,
    },
    Ping {
        host: String,
    },
    Tcp {
        host: String,
        port: u16,
        #[serde(default, rename = "send", alias = "send_message")]
        send_message: Option<String>,
        #[serde(default, rename = "response_end", alias = "response_terminator")]
        response_terminator: Option<String>,
        #[serde(
            default = "default_tcp_max_response_bytes",
            rename = "max_bytes",
            alias = "max_response_bytes"
        )]
        max_response_bytes: usize,
    },
}

#[derive(Clone, Copy, Debug, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum ResponseCodeStatus {
    Operational,
    Degraded,
    Down,
}

fn default_tcp_max_response_bytes() -> usize {
    16 * 1024
}

fn default_method() -> String {
    "GET".to_owned()
}
